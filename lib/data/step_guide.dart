/// 단계 이름에 맞는 설명 목록 (중복 제거, 규칙 순서 유지)
List<String> stepGuide(String stepName, BakeCategory cat) {
  final out = <String>{};
  for (final r in _rules) {
    if (r.re.hasMatch(stepName)) out.addAll(r.guide(cat));
  }
  return out.toList();
}

bool isWeighStep(String stepName) => stepName.contains('재료 계량');
bool isGravityStep(String stepName) => stepName.contains('비중');

/// 배합표 한 줄
class RecipeLine {
  const RecipeLine(this.name, this.amount);
  final String name;
  final String amount;
}

final RegExp _recipeRe = RegExp(r'^(.+?)[\s:]+([\d.,]+\s*(?:g|kg|ml|개|%)?)\s*$', caseSensitive: false);

/// "재료이름 무게" 형식의 여러 줄 텍스트를 재료 목록으로 변환
List<RecipeLine> parseRecipe(String text) => text
    .split('\n')
    .map((l) => l.trim())
    .where((l) => l.isNotEmpty)
    .map((l) {
      final m = _recipeRe.firstMatch(l);
      return m != null ? RecipeLine(m.group(1)!.trim(), m.group(2)!) : RecipeLine(l, '');
    })
    .toList();

/// 비중 = (컵+반죽 - 컵) / (컵+물 - 컵). 계산할 수 없으면 null
double? specificGravity({double? cup, double? cupWater, double? cupDough}) {
  if (cup == null || cupWater == null || cupDough == null) return null;
  if (cupWater <= cup) return null;
  return (cupDough - cup) / (cupWater - cup);
}
