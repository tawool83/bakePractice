function recipeOf(cat,id){return (S.prefs.recipes&&S.prefs.recipes[cat+':'+id])||'';}
function parseRecipe(t){return t.split(/\n/).map(l=>l.trim()).filter(Boolean).map(l=>{
  const m=l.match(/^(.+?)[\s:]+([\d.,]+\s*(?:g|kg|ml|개|%)?)\s*$/i);return m?{n:m[1].trim(),a:m[2]}:{n:l,a:''};});}
function detailHTML(name,cat,id,live,idx){
  let b=[];RULES.forEach(([re,f])=>{if(re.test(name))b.push(...f(cat));});
  b=[...new Set(b)];
  let h=b.length?'<ul>'+b.map(x=>'<li>'+esc(x)+'</li>').join('')+'</ul>':'<p class="sub" style="margin:0">공개문제 요구사항대로 진행해.</p>';
  if(/재료 계량/.test(name)){
    const rs=parseRecipe(recipeOf(cat,id));
    if(!rs.length){h+='<p class="sub">배합표를 입력하면 여기서 재료별로 체크하면서 계량할 수 있어. 과제 준비 화면의 배합표 칸에 넣어줘.</p>';}
    else if(live){const w=S.active.weighed||[];
      h+='<p class="sub">계량 체크 ('+w.filter(Boolean).length+'/'+rs.length+')</p><div class="wlist">'+rs.map((r,i)=>'<label class="'+(w[i]?'got':'')+'"><input type="checkbox" data-wi="'+i+'" '+(w[i]?'checked':'')+'><span>'+esc(r.n)+'</span><span class="amt">'+esc(r.a)+'</span></label>').join('')+'</div>';}
    else{h+='<p class="sub">내 배합표</p><div class="wlist">'+rs.map(r=>'<label><span>'+esc(r.n)+'</span><span class="amt">'+esc(r.a)+'</span></label>').join('')+'</div>';}
  }
  if(/비중/.test(name)){
    h+='<p class="sub">비중 계산기 (g)</p><div class="bjcalc"><label><span>빈 컵</span><input type="number" inputmode="decimal" data-bj="c"></label><label><span>컵+물</span><input type="number" inputmode="decimal" data-bj="w"></label><label><span>컵+반죽</span><input type="number" inputmode="decimal" data-bj="d"></label></div><div class="bjout">비중 -</div>';
  }
  return h;
}
